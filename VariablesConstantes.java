package holamundo;

public class VariablesConstantes {

    public static void main(String[] args) {
        // Variables
        String nombre = "ernesto";
        System.out.println(nombre);

        nombre = "pamela";
        System.out.println(nombre);

        var correo = "pame12@gmail.com";
        System.out.println(correo);

        var anio = 2024;
        System.out.println(anio);

        // Constantes
        final String CORREO_OFICIAL = "Pamef@gmail.com";
        System.out.println(CORREO_OFICIAL);
    }
}